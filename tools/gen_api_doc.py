"""Regenerate docs/api.md from the command registry.  Run:  python tools/gen_api_doc.py"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from japy import JapyInterpreter, VERSION_LABEL  # noqa: E402

ORDER = ["Output", "Types", "Math", "Text", "Lists", "Dicts", "JSON", "Time", "Engine", "Constants",
         "3D", "2D", "Physics", "Mobile UI", "Audio", "Input", "Scenes", "Network", "Save data"]


def main():
    interp = JapyInterpreter()
    groups = {}
    for name, (category, signature, description) in interp.docs.items():
        groups.setdefault(category, []).append((name, signature, description))
    total = sum(len(v) for v in groups.values())
    out = ["# Japy Command Reference (%s)" % VERSION_LABEL, "",
           "%d commands and constants are built in right now. This file is generated by "
           "`python tools/gen_api_doc.py`; inside a script, `help(\"name\")` and `listapis(\"prefix\")` "
           "show the same information." % total, "",
           "Commands marked *(simulated)* print what a real engine back end would do; they do not draw "
           "or play anything yet.", ""]
    for category in ORDER + sorted(set(groups) - set(ORDER)):
        if category not in groups:
            continue
        out.append("## %s (%d)" % (category, len(groups[category])))
        out.append("")
        out.append("| Command | What it does |")
        out.append("| --- | --- |")
        for name, signature, description in sorted(groups[category]):
            out.append("| `%s` | %s |" % (signature, description.replace("|", "\\|")))
        out.append("")
    with open(os.path.join(ROOT, "docs", "api.md"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(out))
    print("docs/api.md written (%d commands)" % total)


if __name__ == "__main__":
    main()
